def main() -> None:
    PLAN.mkdir(parents=True, exist_ok=True)
    tasks_out = []
    for tid, title, gate, goal, steps in TASKS:
        assert len(steps) == 20, (tid, len(steps))
        task = {
            "id": tid,
            "title": title,
            "goal": goal,
            "decision_interview": gate,
            "status": "pending",
            "steps": [
                {
                    "step": i + 1,
                    "action": step,
                    "exit_criteria": f"Evidence in repo or decision log for {tid} step {i+1}",
                }
                for i, step in enumerate(steps)
            ],
        }
        tasks_out.append(task)
        lines = [
            f"# {tid}: {title}",
            "",
            f"**Goal:** {goal}",
            f"**Decision interview:** {gate}",
            "",
            "## 20-step completion plan",
            "",
        ]
        for s in task["steps"]:
            lines += [f"### Step {s['step']}: {s['action']}", "", f"- Exit criteria: {s['exit_criteria']}", ""]
        (PLAN / f"{tid}.md").write_text("\n".join(lines))

    master = {
        "project": "hire-ready-portfolio",
        "objective": "Complete professional personal portfolio to get hired ASAP",
        "rule": "Decision interviews always before moving forward past a major gate",
        "tasks": tasks_out,
        "completion_subtasks": [{"id": a, "title": b, "done_when": c} for a, b, c in COMPLETION],
    }
    (PLAN / "master-plan.json").write_text(json.dumps(master, indent=2) + "\n")
    idx = ["# Hire-ready portfolio master plan", "", "Decision interviews always before moving forward.", "", "## 10 completion subtasks", ""]
    for a, b, c in COMPLETION:
        idx += [f"### {a}: {b}", "", f"- Done when: {c}", ""]
    idx += ["## 20 tasks", ""]
    for t in tasks_out:
        idx.append(f"1. [{t['id']}: {t['title']}]({t['id']}.md) — `{t['decision_interview']}`")
    (PLAN / "README.md").write_text("\n".join(idx) + "\n")
    print(f"wrote {len(tasks_out)} specialized tasks")


if __name__ == "__main__":
    main()
