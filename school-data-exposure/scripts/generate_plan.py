def step_detail(task: dict, n: int, phase: str) -> dict:
    return {
        "step": n,
        "action": phase,
        "inputs": f"Outputs of prior steps in {task['id']} plus locked decisions up to {task['decision_interview']}",
        "procedure": [
            f"Re-read {task['id']} goal: {task['goal']}",
            f"Confirm gate {task['decision_interview']} is not violated by this step",
            f"Execute: {phase}",
            "Save artifacts under school-data-exposure/ with citations",
            "Update plan/status.json for this step",
        ],
        "exit_criteria": f"'{phase}' is evidenced in the working tree or decision log",
        "blocks_forward": n == 20,
    }


def main() -> None:
    PLAN.mkdir(parents=True, exist_ok=True)
    tasks_out = []
    for task in TASKS:
        steps = [step_detail(task, i + 1, p) for i, p in enumerate(task["phases"])]
        assert len(steps) == 20, task["id"]
        tasks_out.append(
            {
                "id": task["id"],
                "title": task["title"],
                "goal": task["goal"],
                "decision_interview": task["decision_interview"],
                "status": "pending",
                "steps": steps,
            }
        )

    master = {
        "project": "school-data-exposure",
        "title": "Expose how school systems collect, use, and abuse student data",
        "provisional_defaults": PROVISIONAL,
        "rule": "No forward movement past a major gate without a recorded decision interview",
        "tasks": tasks_out,
        "completion_subtasks": COMPLETION_SUBTASKS,
    }

    (PLAN / "master-plan.json").write_text(json.dumps(master, indent=2) + "\n")

    # Per-task markdown
    for t in tasks_out:
        lines = [
            f"# {t['id']}: {t['title']}",
            "",
            f"**Goal:** {t['goal']}",
            f"**Decision interview before completion:** {t['decision_interview']}",
            f"**Status:** {t['status']}",
            "",
            "## 20-step completion plan",
            "",
        ]
        for s in t["steps"]:
            lines.append(f"### Step {s['step']}: {s['action']}")
            lines.append("")
